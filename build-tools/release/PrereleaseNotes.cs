using System.Text;
using System.Text.RegularExpressions;

namespace TiaMcp.ReleaseTool;

// The "Not verified on a real TIA Portal" section of pre-release notes. It is generated from two tracked sources, the real-machine
// ledger and the API audit VM checklist, so testers see every item that only offline checks cover. Plain releases do not use it.
// Every item carries one running number across the whole section, which the pre-release report form asks for.
internal static class PrereleaseNotes
{
    internal const string Begin = "<!-- generated:not-verified:begin -->";
    internal const string End = "<!-- generated:not-verified:end -->";
    internal const string Heading = "## Not verified on a real TIA Portal";
    internal const string LedgerPath = "docs/reference/real-machine-ledger.md";
    internal const string ChecklistPath = "docs/reference/api-audit-vm-checklist.md";
    // Neither source ships in the package, so the notes link to them on GitHub.
    private const string Repository = "https://github.com/asckye/TIA_Portal_Openness_MCP/blob/master/";

    // Ledger sections whose table rows are open real-machine items for the next release. A renamed or removed section fails the generator.
    internal static readonly string[] LedgerSections =
    [
        "未发布改动的验收边界",
        "V20/V21 host + worker acceptance (P6-54)",
        "4.0 安全策略验收计划（P6-R2）",
        "4.0 发布前仍需的真实机器步骤"
    ];

    internal static string NotesPath(string version) => "docs/releases/v" + version + ".md";

    internal static string Generate(string ledger, string checklist)
    {
        ledger = ledger.Replace("\r\n", "\n", StringComparison.Ordinal);
        checklist = checklist.Replace("\r\n", "\n", StringComparison.Ordinal);
        var text = new StringBuilder();
        text.Append(Begin).Append('\n');
        text.Append(Heading).Append("\n\n");
        text.Append("Generated by `generate-prerelease-notes` from [the real-machine ledger](" + Repository + "docs/reference/real-machine-ledger.md) and ")
            .Append("[the API audit VM checklist](" + Repository + "docs/reference/api-audit-vm-checklist.md). Builds, offline suites and CI passed for this ")
            .Append("pre-release; none of the items below has been run against a real TIA Portal. Please report what you check with the item ")
            .Append("number, the TIA version and the exact steps.\n\n");
        var number = 0;
        text.Append("### Real-machine ledger\n\n");
        foreach (var section in LedgerSections)
        {
            var rows = SectionRows(ledger, section);
            if (rows.Count == 0) throw new ReleaseException("Real-machine ledger section has no table rows: " + section);
            text.Append("#### ").Append(section).Append("\n\n");
            foreach (var row in rows) text.Append(++number).Append(". ").Append(row).Append('\n');
            text.Append('\n');
        }
        var behavior = Regex.Matches(ledger, "^\\| [^|\\n]+ \\| [^|\\n]+ \\| current \\| NOT RUN \\|", RegexOptions.Multiline).Count;
        if (behavior == 0) throw new ReleaseException("Real-machine ledger has no generated behavior-capability rows");
        text.Append("#### Behavior capabilities\n\n");
        text.Append(++number).Append(". All ").Append(behavior).Append(" release/family rows of the generated behavior-capability table in the ledger are `current` with L5 NOT RUN.\n\n");
        text.Append("### API audit VM checklist\n\n");
        // The checklist numbers its items per section and lists the pending findings as bullets; in the notes each top-level item
        // takes the next running number. Continuation lines are indented and stay as they are.
        var body = Regex.Replace(AbsoluteLinks(ChecklistBody(checklist), "docs/reference/"), "^(?:\\d+\\.|-) ",
            _ => (++number).ToString(System.Globalization.CultureInfo.InvariantCulture) + ". ", RegexOptions.Multiline);
        text.Append(body.TrimEnd('\n')).Append("\n\n");
        text.Append(End).Append('\n');
        return text.ToString();
    }

    /// <summary>The notes with the generated block replaced; null when the notes have no complete marker pair.</summary>
    internal static string? Apply(string notes, string block)
    {
        var start = notes.IndexOf(Begin, StringComparison.Ordinal);
        var finish = start < 0 ? -1 : notes.IndexOf(End, start, StringComparison.Ordinal);
        if (start < 0 || finish < 0 || notes.IndexOf(Begin, start + Begin.Length, StringComparison.Ordinal) >= 0) return null;
        var after = finish + End.Length;
        if (after < notes.Length && notes[after] == '\n') after++;
        else if (after + 1 < notes.Length && notes[after] == '\r' && notes[after + 1] == '\n') after += 2;
        var newline = notes.Contains("\r\n", StringComparison.Ordinal) ? "\r\n" : "\n";
        return notes[..start] + block.Replace("\n", newline, StringComparison.Ordinal) + notes[after..];
    }

    /// <summary>The expected notes content for a pre-release, or an error.</summary>
    internal static (string? Notes, string? Error) Expected(string root, string version)
    {
        var notesPath = Path.Combine(root, NotesPath(version));
        if (!File.Exists(notesPath)) return (null, NotesPath(version) + " is missing - write the release note first");
        foreach (var source in new[] { LedgerPath, ChecklistPath })
            if (!File.Exists(Path.Combine(root, source))) return (null, "Pre-release notes source missing: " + source);
        string block;
        try { block = Generate(File.ReadAllText(Path.Combine(root, LedgerPath)), File.ReadAllText(Path.Combine(root, ChecklistPath))); }
        catch (ReleaseException error) { return (null, error.Message); }
        var notes = File.ReadAllText(notesPath);
        var updated = Apply(notes, block);
        return updated is null
            ? (null, NotesPath(version) + " needs exactly one " + Begin + " ... " + End + " block for the generated not-verified section")
            : (updated, null);
    }

    /// <summary>Null when the notes of a pre-release carry the current generated section.</summary>
    internal static string? CurrentError(string root, string version)
    {
        var (expected, error) = Expected(root, version);
        if (error is not null) return error;
        var actual = File.ReadAllBytes(Path.Combine(root, NotesPath(version)));
        return actual.AsSpan().SequenceEqual(Encoding.UTF8.GetBytes(expected!)) ? null
            : NotesPath(version) + " has a stale not-verified section; run generate-prerelease-notes -Version " + version;
    }

    /// <summary>True when published notes text still carries a complete generated section with its heading.</summary>
    internal static bool HasSection(string notes)
    {
        var start = notes.IndexOf(Begin, StringComparison.Ordinal);
        var finish = start < 0 ? -1 : notes.IndexOf(End, start, StringComparison.Ordinal);
        return start >= 0 && finish > start && notes.IndexOf(Heading, start, finish - start, StringComparison.Ordinal) >= 0;
    }

    private static List<string> SectionRows(string ledger, string section)
    {
        var heading = Regex.Match(ledger, "^#{2,3} " + Regex.Escape(section) + "[ \\t]*$", RegexOptions.Multiline);
        if (!heading.Success) throw new ReleaseException("Real-machine ledger section missing: " + section);
        // A section ends at the next heading or at a generated block marker (the behavior-capability table follows the last section).
        var next = Regex.Match(ledger[(heading.Index + heading.Length)..], "^(?:#{1,3} |<!--)", RegexOptions.Multiline);
        var body = next.Success ? ledger.Substring(heading.Index + heading.Length, next.Index) : ledger[(heading.Index + heading.Length)..];
        var rows = new List<string>();
        var table = 0;
        foreach (var line in body.Split('\n'))
        {
            if (!line.StartsWith('|')) { table = 0; continue; }
            table++;
            if (table <= 2) continue; // header and separator rows
            var cells = line.Trim().Trim('|').Split('|').Select(cell => cell.Trim()).Where(cell => cell.Length != 0).ToArray();
            if (cells.Length == 0) continue;
            var row = cells.Length == 1 ? cells[0] : "**" + cells[0].Replace("**", "", StringComparison.Ordinal) + "**: " + string.Join(" — ", cells.Skip(1));
            rows.Add(AbsoluteLinks(row, "docs/reference/"));
        }
        return rows;
    }

    // Shipped notes may only link shipped files; a ledger link points into the repository, so it becomes a GitHub link.
    internal static string AbsoluteLinks(string text, string directory) =>
        Regex.Replace(text, @"\]\((?!https?:|#|mailto:)([^)\s]+)\)", match =>
        {
            var parts = new List<string>(directory.TrimEnd('/').Split('/'));
            foreach (var part in match.Groups[1].Value.Split('/'))
            {
                if (part == "..") { if (parts.Count > 0) parts.RemoveAt(parts.Count - 1); }
                else if (part is not ("." or "")) parts.Add(part);
            }
            return "](" + Repository + string.Join('/', parts) + ")";
        });

    private static string ChecklistBody(string checklist)
    {
        var first = Regex.Match(checklist, "^## ", RegexOptions.Multiline);
        if (!first.Success) throw new ReleaseException("API audit VM checklist has no \"## \" section");
        var body = checklist[first.Index..];
        // Demote the checklist headings below "### API audit VM checklist".
        return Regex.Replace(body, "^(#{2,4}) ", match => "##" + match.Groups[1].Value + " ", RegexOptions.Multiline);
    }

    internal static Dictionary<string, string> Outputs(string root, string version)
    {
        var parsed = ReleaseVersions.Require(version, "-Version must be X.Y.Z-beta.N or X.Y.Z-rc.N");
        if (!parsed.IsPrerelease) throw new ReleaseException("generate-prerelease-notes only writes pre-release notes (X.Y.Z-beta.N or X.Y.Z-rc.N)", 64);
        var (expected, error) = Expected(root, parsed.Label);
        if (error is not null) throw new ReleaseException(error);
        return new() { [NotesPath(parsed.Label)] = expected! };
    }
}
