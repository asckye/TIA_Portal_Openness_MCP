using System.Text;
using System.Text.Json;
using System.Text.Json.Serialization;
using System.Text.RegularExpressions;

namespace TiaMcp.ReleaseTool;

// Pre-release notes summarize recorded tool executions and list outstanding ledger and API checklist items.
// Every item carries one running number across the whole section, which the pre-release report form asks for.
internal static class PrereleaseNotes
{
    internal const string Begin = "<!-- generated:not-verified:begin -->";
    internal const string End = "<!-- generated:not-verified:end -->";
    internal const string Heading = "## Not verified on a real TIA Portal";
    internal const string Chinese = "## 中文";
    internal const string English = "## English";
    internal const string ChineseHeading = "## 尚待 TIA Portal 真机验证";
    internal const string TranslationsPath = "build-tools/release/prerelease-translations.json";
    internal const string LedgerPath = "docs/reference/real-machine-ledger.md";
    internal const string ChecklistPath = "docs/reference/api-audit-vm-checklist.md";
    // Neither source ships in the package, so the notes link to them on GitHub.
    private const string Repository = "https://github.com/asckye/TIA_Portal_Openness_MCP/blob/master/";

    // Ledger sections whose table rows are open real-machine items for the next release. A renamed or removed section fails the generator.
    internal static readonly string[] LedgerSections =
    [
        "未发布改动的验收边界",
        "V20/V21 host + worker acceptance (P6-54)",
        "4.0 安全策略验收计划（P6-R2）",
        "4.0 发布前仍需的真实机器步骤"
    ];

    internal static string NotesPath(string version) => "docs/releases/v" + version + ".md";

    internal static bool Published(string root, string version)
    {
        if (File.Exists(Path.Combine(root, "manifest", $"publication-v{version}.json"))) return true;
        if (!Path.Exists(Path.Combine(root, ".git"))) return false;
        // The publisher creates refs/tags/v<version>. Use the exact local ref for offline release checks.
        var tag = "v" + version;
        var result = ReviewChangeSet.Git("git", ["tag", "--list", tag], root);
        ProcessRunner.RequireSuccess(result, "read local release tags");
        return result.StandardOutput.TrimEnd() == tag;
    }

    internal sealed record Translation([property: JsonPropertyName("zh")] string Zh,
        [property: JsonPropertyName("en")] string En);

    private static int EnglishStart(string notes)
    {
        var languages = Regex.Matches(notes, @"^(?:## 中文|## English)\r?$", RegexOptions.Multiline);
        return languages.Count == 2 && languages[0].Value.TrimEnd() == Chinese && languages[1].Value.TrimEnd() == English
            ? languages[1].Index : -1;
    }

    internal static int RequireLanguages(string notes)
    {
        int split = EnglishStart(notes);
        if (split < 0) throw new ReleaseException("Release notes require ## 中文 followed by ## English.");
        return split;
    }

    internal static string DraftBlock(string ledger, string checklist, RealMachineStatusGenerator.Table status,
        IReadOnlyList<Translation> translations, bool chinese)
    {
        string Normalize(string value) => Regex.Replace(value.Trim(), @"\s+", " ");
        var lookup = new Dictionary<string, string>(StringComparer.Ordinal);
        foreach (var pair in translations)
        {
            if (string.IsNullOrWhiteSpace(pair.Zh) || string.IsNullOrWhiteSpace(pair.En))
                throw new ReleaseException($"Each entry in {TranslationsPath} requires both zh and en.");
            var output = chinese ? pair.Zh : pair.En;
            lookup[Normalize(pair.Zh)] = output;
            lookup[Normalize(pair.En)] = output;
        }
        string Localize(string source)
        {
            string key = Normalize(source);
            if (!lookup.TryGetValue(key, out var target))
                throw new ReleaseException($"Missing release-note translation in {TranslationsPath}: {key}");
            return Normalize(target) == key ? source : target;
        }
        ledger = ledger.Replace("\r\n", "\n", StringComparison.Ordinal);
        checklist = checklist.Replace("\r\n", "\n", StringComparison.Ordinal);
        var text = new StringBuilder();
        text.Append(Begin).Append('\n');
        text.Append(chinese ? ChineseHeading : Heading).Append("\n\n");
        if (chinese)
        {
            text.Append("本清单由 `generate-prerelease-notes` 根据[真机台账](").Append(Repository).Append(LedgerPath)
                .Append(")和 [API 审计 VM 核对清单](").Append(Repository).Append(ChecklistPath)
                .Append(")生成。本次预发布已通过构建与离线套件。请在报告中注明下列项目编号、TIA 版本和实际步骤。\n\n")
                .Append("[逐工具、逐版真机记录](").Append(Repository).Append(RealMachineStatusGenerator.Page)
                .Append(")。数量包括最近一次测试在较早候选上执行的工具，表中以 ᵒ 标记。\n\n");
        }
        else
        {
            text.Append("Generated by `generate-prerelease-notes` from [the real-machine ledger](" + Repository + "docs/reference/real-machine-ledger.md) and ")
                .Append("[the API audit VM checklist](" + Repository + "docs/reference/api-audit-vm-checklist.md). Builds and offline suites passed for this ")
                .Append("pre-release. The checklist below tracks outstanding acceptance work. Please report what you check with the item ")
                .Append("number, the TIA version and the exact steps.\n\n");
            text.Append("[Real-machine records by tool and release](" + Repository + RealMachineStatusGenerator.Page + "). ")
                .Append("Counts include tools last exercised on an earlier candidate, marked ᵒ in the table.\n\n");
        }
        foreach (var key in CatalogJson.Keys)
        {
            var s = status.Summarize(key);
            if (chinese)
            {
                text.Append($"{RealMachineStatusGenerator.Label(key)} 真机记录：{s.Recorded}/{s.Registered} 个工具（候选 {s.Latest?.Commit ?? "—"}）\n\n");
                continue;
            }
            text.Append($"Real-machine records: {s.Recorded}/{s.Registered} tools on {RealMachineStatusGenerator.Label(key)}")
                .Append($" (candidate {s.Latest?.Commit ?? "—"})\n\n");
        }
        var number = 0;
        text.Append(chinese ? "### 真机台账\n\n" : "### Real-machine ledger\n\n");
        foreach (var section in LedgerSections)
        {
            var rows = SectionRows(ledger, section);
            if (rows.Count == 0) throw new ReleaseException("Real-machine ledger section has no table rows: " + section);
            text.Append("#### ").Append(Localize(section)).Append("\n\n");
            foreach (var row in rows) text.Append(++number).Append(". ").Append(AbsoluteLinks(Localize(row), "docs/reference/")).Append('\n');
            text.Append('\n');
        }
        var behavior = Regex.Matches(ledger, "^\\| [^|\\n]+ \\| [^|\\n]+ \\| current \\| NOT RUN \\|", RegexOptions.Multiline).Count;
        if (behavior == 0) throw new ReleaseException("Real-machine ledger has no generated behavior-capability rows");
        text.Append(chinese ? "#### 行为能力\n\n" : "#### Behavior capabilities\n\n");
        text.Append(++number).Append(chinese
            ? $". 台账中行为能力表的 {behavior} 条版本/行为族记录均为 `current`，L5 均为 NOT RUN。\n\n"
            : $". All {behavior} release/family rows of the generated behavior-capability table in the ledger are `current` with L5 NOT RUN.\n\n");
        text.Append(chinese ? "### API 审计 VM 核对清单\n\n" : "### API audit VM checklist\n\n");
        var body = ChecklistBody(checklist).TrimEnd();
        // Preserve paragraph breaks and the original indentation of continuation lines.
        var localized = Regex.Replace(body, @"^(?<prefix>#{2,6} |\d+\. |- )?(?<item>[^\n]+(?:\n(?!\n|#{2,6} |\d+\. |- )[^\n]+)*)",
            match =>
            {
                var prefix = match.Groups["prefix"].Value;
                if (prefix.Length > 0 && prefix[0] != '#') prefix = (++number).ToString(System.Globalization.CultureInfo.InvariantCulture) + ". ";
                return prefix + Localize(match.Groups["item"].Value);
            }, RegexOptions.Multiline);
        text.Append(AbsoluteLinks(localized, "docs/reference/")).Append("\n\n");
        text.Append(End).Append('\n');
        return text.ToString();
    }

    /// <summary>The notes with the generated block replaced; null when the notes have no complete marker pair.</summary>
    internal static string? Apply(string notes, string block)
    {
        var start = notes.IndexOf(Begin, StringComparison.Ordinal);
        var finish = start < 0 ? -1 : notes.IndexOf(End, start, StringComparison.Ordinal);
        if (start < 0 || finish < 0 || notes.IndexOf(Begin, start + Begin.Length, StringComparison.Ordinal) >= 0
            || notes.IndexOf(End, StringComparison.Ordinal) != finish || notes.IndexOf(End, finish + End.Length, StringComparison.Ordinal) >= 0) return null;
        var after = finish + End.Length;
        if (after < notes.Length && notes[after] == '\n') after++;
        else if (after + 1 < notes.Length && notes[after] == '\r' && notes[after + 1] == '\n') after += 2;
        var newline = notes.Contains("\r\n", StringComparison.Ordinal) ? "\r\n" : "\n";
        return notes[..start] + block.Replace("\n", newline, StringComparison.Ordinal) + notes[after..];
    }

    /// <summary>The expected notes content for a pre-release, or an error.</summary>
    private static (string? Notes, string? Error) Generate(string root, string version)
    {
        var notesPath = Path.Combine(root, NotesPath(version));
        if (!File.Exists(notesPath)) return (null, NotesPath(version) + " is missing - write the release note first");
        if (Published(root, version))
        {
            var frozen = Encoding.UTF8.GetString(File.ReadAllBytes(notesPath));
            var split = EnglishStart(frozen);
            if (split >= 0 ? !HasBilingualSections(frozen) : !HasSection(frozen) || Apply(frozen, "") is null)
                return (null, NotesPath(version) + " needs its published not-verified section");
            if (Path.Exists(Path.Combine(root, ".git")))
            {
                var diff = ReviewChangeSet.Git("git", ["diff", "--quiet", "HEAD", "--", NotesPath(version)], root);
                if (diff.ExitCode == 1) return (null, NotesPath(version) + " differs from the frozen release notes in HEAD");
                ProcessRunner.RequireSuccess(diff, "verify frozen release notes");
            }
            return (frozen, null);
        }
        foreach (var source in new[] { LedgerPath, ChecklistPath, RealMachineStatusGenerator.Roster, RealMachineStatusGenerator.Manifest, TranslationsPath })
            if (!File.Exists(Path.Combine(root, source))) return (null, "Pre-release notes source missing: " + source);
        var sourceNotes = File.ReadAllText(notesPath);
        try
        {
            var split = RequireLanguages(sourceNotes);
            var blocks = DraftBlocks(root);
            var zh = Apply(sourceNotes[..split], blocks.Chinese);
            var en = Apply(sourceNotes[split..], blocks.English);
            if (zh is null || en is null) throw new ReleaseException("Each language section needs one " + Begin + " ... " + End + " block.");
            return (zh + en, null);
        }
        catch (ReleaseException error) { return (null, error.Message); }
    }

    internal static (string Chinese, string English) DraftBlocks(string root)
    {
        var ledger = File.ReadAllText(Path.Combine(root, LedgerPath));
        var checklist = File.ReadAllText(Path.Combine(root, ChecklistPath));
        var status = RealMachineStatusGenerator.Read(root);
        var translations = ReadTranslations(root);
        return (DraftBlock(ledger, checklist, status, translations, chinese: true),
            DraftBlock(ledger, checklist, status, translations, chinese: false));
    }

    internal static Translation[] ReadTranslations(string root) =>
        JsonSerializer.Deserialize<Translation[]>(File.ReadAllText(Path.Combine(root, TranslationsPath)))
        ?? throw new ReleaseException("Missing release-note translations.");

    internal static bool HasBilingualSections(string notes)
    {
        int split = EnglishStart(notes);
        if (split < 0) return false;
        var zh = notes[..split];
        var en = notes[split..];
        return HasSection(zh, ChineseHeading) && HasSection(en) && Apply(zh, "") != null && Apply(en, "") != null;
    }

    /// <summary>Null when the notes of a pre-release carry the current generated section.</summary>
    internal static string? CurrentError(string root, string version)
    {
        var (expected, error) = Generate(root, version);
        if (error is not null) return error;
        var actual = File.ReadAllBytes(Path.Combine(root, NotesPath(version)));
        return actual.AsSpan().SequenceEqual(Encoding.UTF8.GetBytes(expected!)) ? null
            : NotesPath(version) + " has a stale not-verified section; run generate-prerelease-notes -Version " + version;
    }

    /// <summary>True when published notes text still carries a complete generated section with its heading.</summary>
    internal static bool HasSection(string notes, string heading = Heading)
    {
        var start = notes.IndexOf(Begin, StringComparison.Ordinal);
        var finish = start < 0 ? -1 : notes.IndexOf(End, start, StringComparison.Ordinal);
        return start >= 0 && finish > start && notes.IndexOf(heading, start, finish - start, StringComparison.Ordinal) >= 0;
    }

    private static List<string> SectionRows(string ledger, string section)
    {
        var heading = Regex.Match(ledger, "^#{2,3} " + Regex.Escape(section) + "[ \\t]*$", RegexOptions.Multiline);
        if (!heading.Success) throw new ReleaseException("Real-machine ledger section missing: " + section);
        // A section ends at the next heading or at a generated block marker (the behavior-capability table follows the last section).
        var next = Regex.Match(ledger[(heading.Index + heading.Length)..], "^(?:#{1,3} |<!--)", RegexOptions.Multiline);
        var body = next.Success ? ledger.Substring(heading.Index + heading.Length, next.Index) : ledger[(heading.Index + heading.Length)..];
        var rows = new List<string>();
        var table = 0;
        foreach (var line in body.Split('\n'))
        {
            if (!line.StartsWith('|')) { table = 0; continue; }
            table++;
            if (table <= 2) continue; // header and separator rows
            var cells = line.Trim().Trim('|').Split('|').Select(cell => cell.Trim()).Where(cell => cell.Length != 0).ToArray();
            if (cells.Length == 0) continue;
            var row = cells.Length == 1 ? cells[0] : "**" + cells[0].Replace("**", "", StringComparison.Ordinal) + "**: " + string.Join(" — ", cells.Skip(1));
            rows.Add(row);
        }
        return rows;
    }

    // Shipped notes may only link shipped files; a ledger link points into the repository, so it becomes a GitHub link.
    internal static string AbsoluteLinks(string text, string directory) =>
        Regex.Replace(text, @"\]\((?!https?:|#|mailto:)([^)\s]+)\)", match =>
        {
            var parts = new List<string>(directory.TrimEnd('/').Split('/'));
            foreach (var part in match.Groups[1].Value.Split('/'))
            {
                if (part == "..") { if (parts.Count > 0) parts.RemoveAt(parts.Count - 1); }
                else if (part is not ("." or "")) parts.Add(part);
            }
            return "](" + Repository + string.Join('/', parts) + ")";
        });

    private static string ChecklistBody(string checklist)
    {
        var first = Regex.Match(checklist, "^## ", RegexOptions.Multiline);
        if (!first.Success) throw new ReleaseException("API audit VM checklist has no \"## \" section");
        var body = checklist[first.Index..];
        // Demote the checklist headings below "### API audit VM checklist".
        return Regex.Replace(body, "^(#{2,4}) ", match => "##" + match.Groups[1].Value + " ", RegexOptions.Multiline);
    }

    internal static Dictionary<string, string> Outputs(string root, string version)
    {
        var parsed = ReleaseVersions.Require(version, "-Version must be X.Y.Z-beta.N or X.Y.Z-rc.N");
        if (!parsed.IsPrerelease) throw new ReleaseException("generate-prerelease-notes only writes pre-release notes (X.Y.Z-beta.N or X.Y.Z-rc.N)", 64);
        var (expected, error) = Generate(root, parsed.Label);
        if (error is not null) throw new ReleaseException(error);
        return new() { [NotesPath(parsed.Label)] = expected! };
    }
}
