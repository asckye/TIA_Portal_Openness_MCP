using System.Text.RegularExpressions;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;
using Microsoft.CodeAnalysis.Text;

namespace TiaMcp.ReleaseTool;

internal static partial class WrapLongLines
{
    private sealed record ChangedFile(string Path, string OldPath, string Status);
    private sealed record ChangedLine(int Number, int? PreviousLength = null);

    private static IEnumerable<ChangedLine> ChangedLines(string patch, string before)
    {
        var oldLines = SourceText.From(before).Lines;
        foreach (Match hunk in Regex.Matches(patch, @"(?m)^@@ -(\d+)(?:,(\d+))? \+(\d+)(?:,(\d+))? @@"))
        {
            int Number(int group) => int.Parse(hunk.Groups[group].Value, System.Globalization.CultureInfo.InvariantCulture);
            int oldStart = Number(1), oldCount = hunk.Groups[2].Success ? Number(2) : 1;
            int newStart = Number(3), newCount = hunk.Groups[4].Success ? Number(4) : 1;
            int? longest = oldCount == 0 ? null : Enumerable.Range(oldStart - 1, oldCount).Max(n => oldLines[n].Span.Length);
            for (int index = 0; index < newCount; index++)
                yield return new(newStart + index, oldCount == newCount ? oldLines[oldStart - 1 + index].Span.Length : longest);
        }
    }

    private static bool ExcludedSource(string source, string path) => Matches(path, ExcludedFiles)
        || path.EndsWith(".g.cs", StringComparison.OrdinalIgnoreCase)
        || path.EndsWith(".generated.cs", StringComparison.OrdinalIgnoreCase)
        || source.TrimStart().StartsWith("// <auto-generated", StringComparison.OrdinalIgnoreCase);

    private static bool SourcePath(string path) => path.EndsWith(".cs", StringComparison.OrdinalIgnoreCase)
        && !path.Replace('\\', '/').Split('/').Any(part => part is "bin" or "obj");

    private static Dictionary<int, string> MultilineReasons(TextLineCollection lines, string source)
    {
        var reasons = new Dictionary<int, string>();
        void Mark(TextSpan span, string reason)
        {
            for (int n = lines.GetLineFromPosition(span.Start).LineNumber;
                n <= lines.GetLineFromPosition(Math.Max(span.Start, span.End - 1)).LineNumber; n++)
                reasons[n] = reason;
        }
        foreach (var token in Lex(source, true))
        {
            if (token.Kind().ToString().Contains("Interpolated", StringComparison.Ordinal)) Mark(token.Span, "interpolated");
            if (token.Text.StartsWith("@\"", StringComparison.Ordinal) || token.Text.StartsWith("\"\"\"", StringComparison.Ordinal))
                Mark(token.Span, "verbatim-or-raw");
            foreach (var trivia in token.LeadingTrivia.Concat(token.TrailingTrivia).Where(t =>
                t.IsKind(SyntaxKind.MultiLineCommentTrivia) || t.IsKind(SyntaxKind.MultiLineDocumentationCommentTrivia)))
                Mark(trivia.Span, "comment");
        }
        return reasons;
    }

    private static int CheckChanges(string root, Options options, string basis, int maximum)
    {
        string Git(params string[] arguments)
        {
            var result = ReviewChangeSet.Git("git", ["--no-optional-locks", .. arguments], root);
            ProcessRunner.RequireSuccess(result, "Read changed source lines");
            return result.StandardOutput;
        }
        var common = ReviewChangeSet.Basis(root, basis, "git");
        var parts = Git("diff", "--name-status", "-z", "--find-renames", "--break-rewrites", "--no-ext-diff", "--no-textconv", common, "--")
            .Split('\0', StringSplitOptions.RemoveEmptyEntries);
        var files = new List<ChangedFile>();
        for (int index = 0; index < parts.Length;)
        {
            string status = parts[index++], oldPath = parts[index++];
            string path = status.StartsWith('R') || status.StartsWith('C') ? parts[index++] : oldPath;
            files.Add(new(path, oldPath, status));
        }
        var untracked = Git("ls-files", "--others", "--exclude-standard", "-z")
            .Split('\0', StringSplitOptions.RemoveEmptyEntries).Where(SourcePath).ToHashSet(StringComparer.Ordinal);
        // Git cannot see untracked destinations. Pair deleted sources with their closest
        // destination retaining at least half its lines, including pure unstaged moves.
        foreach (var deleted in files.Where(file => file.Status == "D" && SourcePath(file.Path)).ToArray())
        {
            string before = Git("show", common + ":" + deleted.OldPath).Replace("\r\n", "\n", StringComparison.Ordinal);
            string? moved = null;
            double best = 0;
            foreach (var path in untracked.Order(StringComparer.Ordinal))
            {
                var after = File.ReadAllText(Path.Combine(root, path)).Replace("\r\n", "\n", StringComparison.Ordinal);
                double similarity = 1;
                if (before != after)
                {
                    var stat = Git("diff", "--numstat", "--no-ext-diff", "--no-textconv", common + ":" + deleted.OldPath, "--", path)
                        .Split('\t');
                    if (stat.Length < 3 || !int.TryParse(stat[1], out int removed)) continue;
                    int oldCount = SourceText.From(before).Lines.Count, newCount = SourceText.From(after).Lines.Count;
                    similarity = (double)(oldCount - removed) / Math.Max(oldCount, newCount);
                }
                if (similarity < 0.5 || similarity <= best) continue;
                moved = path;
                best = similarity;
            }
            if (moved != null)
            {
                untracked.Remove(moved);
                files.Add(new(moved, deleted.OldPath, "R"));
            }
        }
        bool Selected(string path) => SourcePath(path) && (options.All("Path").Count == 0 || options.All("Path").Any(selection =>
        {
            string full = Path.GetFullPath(selection, root), file = Path.GetFullPath(path, root);
            return file.Equals(full, StringComparison.OrdinalIgnoreCase)
                || file.StartsWith(Path.TrimEndingDirectorySeparator(full) + Path.DirectorySeparatorChar, StringComparison.OrdinalIgnoreCase);
        }));
        Console.WriteLine("Excluded files: bin/ and obj/; *.g.cs, *.generated.cs, // <auto-generated> sources; "
            + string.Join(", ", ExcludedFiles));
        Console.WriteLine("Excluded lines: directives, pinned fragments, interpolated/verbatim/raw/non-ASCII literals and comments.");
        Console.WriteLine("Pinned fragments: " + string.Join(", ", PinnedFragments));
        int failures = 0, checkedLines = 0, excluded = 0;
        void Inspect(string path, IEnumerable<ChangedLine> changes)
        {
            var source = File.ReadAllText(Path.Combine(root, path));
            if (ExcludedSource(source, path)) { excluded++; return; }
            var lines = SourceText.From(source).Lines;
            var spans = new Dictionary<int, TextSpan>();
            string formattedSource = Format(source, path, maximum, spans);
            var formatted = SourceText.From(formattedSource).Lines;
            var multiline = MultilineReasons(formatted, formattedSource);
            foreach (var change in changes.Distinct())
            {
                int number = change.Number;
                var line = lines[number - 1];
                checkedLines++;
                if (line.Span.Length <= maximum) continue;
                if (change.PreviousLength is { } previous && previous > maximum && line.Span.Length <= previous) continue;
                var span = spans[line.LineNumber];
                int first = formatted.GetLineFromPosition(span.Start).LineNumber;
                int last = formatted.GetLineFromPosition(Math.Max(span.Start, span.End - 1)).LineNumber;
                var remaining = Enumerable.Range(first, last - first + 1).Select(n => formatted[n])
                    .Where(fragment => fragment.Span.Length > maximum).ToArray();
                string ReasonFor(TextLine fragment)
                {
                    string reason = Reason(fragment.ToString(), path);
                    return reason is "excluded-file" or "pinned" ? reason : multiline.GetValueOrDefault(fragment.LineNumber) ?? reason;
                }
                if (remaining.Length > 0 && remaining.All(fragment => ReasonFor(fragment) != "no-break-point"
                    || fragment.ToString().TrimStart().StartsWith('#')))
                {
                    Console.WriteLine($"excluded: {path}:{number} ({string.Join(", ", remaining.Select(ReasonFor).Distinct())})");
                    excluded++;
                    continue;
                }
                Console.WriteLine($"{path}:{number}: {line.Span.Length} characters exceeds {maximum}");
                failures++;
            }
        }
        foreach (var file in files.Where(file => file.Status != "D" && Selected(file.Path)))
        {
            if (file.Status == "A")
            {
                Inspect(file.Path, Enumerable.Range(1, SourceText.From(File.ReadAllText(Path.Combine(root, file.Path))).Lines.Count)
                    .Select(n => new ChangedLine(n)));
                continue;
            }
            var patch = Git("diff", "--no-color", "--unified=0", "--inter-hunk-context=0", "--no-ext-diff", "--no-textconv",
                common + ":" + file.OldPath, "--", file.Path);
            Inspect(file.Path, ChangedLines(patch, Git("show", common + ":" + file.OldPath)));
        }
        foreach (var path in untracked.Where(Selected).Order(StringComparer.Ordinal))
            Inspect(path, Enumerable.Range(1, SourceText.From(File.ReadAllText(Path.Combine(root, path))).Lines.Count)
                .Select(n => new ChangedLine(n)));
        Console.WriteLine($"wrap-long-lines: {failures} violations / {checkedLines} changed lines; {excluded} exclusions; base {common}");
        return failures == 0 ? 0 : 1;
    }
}
