using System.Globalization;
using System.Text.Json.Nodes;
using System.Xml.Linq;

namespace TiaMcp.ReleaseTool;

internal static class ToolCountGenerator
{
    internal const string Begin = "<!-- generated:tool-counts:begin -->";
    internal const string End = "<!-- generated:tool-counts:end -->";
    internal static readonly string[] Targets =
    [
        "README.md", "README.zh-CN.md", "docs/getting-started/configuration.md",
        "docs/getting-started/beginners.zh-CN.md", "docs/reference/version-tools.md",
        "docs/releases/v4.0.0.md", "docs/development/runtime-layout.md"
    ];

    internal static Dictionary<string, string> Generate(string root)
    {
        var data = new CatalogData(root);
        var versions = CatalogGenerator.VersionOutputs(data);
        CatalogJson.Require(CatalogJson.Write(root, versions, true) == 0,
            "Generate catalogs before generating documentation tool counts.");
        var resource = XDocument.Load(Path.Combine(root, CatalogGenerator.Resource));
        var runtime = JsonNode.Parse(resource.Root!.Elements("data")
            .Single(e => (string?)e.Attribute("name") == "Catalog").Element("value")!.Value)!;
        var lite = new Dictionary<string, int>();
        foreach (var key in CatalogJson.Keys)
        {
            var rows = runtime["releases"]![key]!.AsArray();
            CatalogJson.Require(rows.Count == data.Rosters[key].Count && data.Rosters[key].SetEquals(rows.Select(r => CatalogJson.Text(r!["currentName"]))),
                "Runtime catalog differs from registered tools: " + key);
            lite[key] = rows.Count(r => CatalogJson.Strings(r!["profiles"]).Contains("lite"));
        }
        return Targets.ToDictionary(path => path, path => Replace(CatalogJson.Source(root, path),
            Render(data, lite, path.EndsWith(".zh-CN.md", StringComparison.Ordinal) ||
                path is "docs/getting-started/configuration.md" or "docs/development/runtime-layout.md",
                path == "docs/releases/v4.0.0.md"), path));
    }

    internal static string Replace(string text, string block, string path)
    {
        var begin = text.IndexOf(Begin, StringComparison.Ordinal);
        var end = text.IndexOf(End, StringComparison.Ordinal);
        CatalogJson.Require(begin >= 0 && end > begin &&
            text.IndexOf(Begin, begin + Begin.Length, StringComparison.Ordinal) < 0 &&
            text.IndexOf(End, end + End.Length, StringComparison.Ordinal) < 0,
            "Expected exactly one tool-count block: " + path);
        return text[..begin] + Begin + "\n" + block + "\n" + text[end..];
    }

    private static string Render(CatalogData data, Dictionary<string, int> lite, bool chinese, bool history)
    {
        var lines = new List<string>
        {
            chinese
                ? "由 `generate-tool-counts` 从 `manifest/version-tools.json` 和 `ToolProfiles.resx` 生成。以运行时 `tools/list` 为准。"
                : "Generated by `generate-tool-counts` from `manifest/version-tools.json` and `ToolProfiles.resx`. Runtime `tools/list` is authoritative.",
            "",
            history ? "| Release key | Archived 3.x | Current V4 | Lite |" : chinese
                ? "| TIA 版本 | 注册工具数 | lite 档 |" : "| TIA release | Registered tools | Lite profile |",
            history ? "|---|---:|---:|---:|" : "|---|---:|---:|"
        };
        foreach (var key in CatalogJson.Keys)
        {
            var label = key switch { "14sp1" => "V14 SP1", "15.1" => "V15.1", _ => "V" + key };
            var count = data.Rosters[key].Count.ToString(CultureInfo.InvariantCulture);
            var small = lite[key] == 0 ? chinese ? "不适用" : "Not applicable"
                : lite[key].ToString(CultureInfo.InvariantCulture);
            lines.Add(history ? $"| `{key}` | {data.Archives[key].Count.ToString(CultureInfo.InvariantCulture)} | {count} | {small} |"
                : $"| {label} | {count} | {small} |");
        }
        if (history) lines.AddRange(["", "Archived counts come from `manifest/history/contracts-v3/baseline`; they describe the frozen 3.x catalogs."]);
        return string.Join('\n', lines);
    }
}
